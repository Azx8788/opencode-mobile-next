#!/usr/bin/env python3
"""Generate aggregated test entrypoints: many small test files in one process.

A standalone ``flutter test`` file costs about 4.4 s of load, compile and
process start for a test that runs in 0.4 s. An entrypoint under build/agg/
imports many test files and calls each ``main`` inside ``group('<path>', ...)``,
so one process pays that cost once. build/ is git-ignored and nothing here is
checked in; both machines generate their entrypoints from their own checkout.

  gen_aggregates.py eligible [--root R] [FILE ...]   print files that may be aggregated
  gen_aggregates.py write --out DIR FILE ...         write DIR/shard_N_test.dart from
                                                     lines "N FILE" read from stdin

Eligibility is decided here by a few source rules and by tool/qa/agg_exclude.txt
(one "path  # reason" per line; every file that failed or hung when aggregated).
A file that fails inside an aggregate is always re-run standalone by
run_tests_split.sh before it counts as failed (tool/qa/split_collect.py).
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

EXCLUDE_FILE = Path("tool/qa/agg_exclude.txt")
# Helpers whose users compare goldens: the comparator resolves a golden next
# to the entrypoint, so those files must run standalone from their own folder.
GOLDEN_HELPERS = (
    "kit_gallery.dart",
    "kit_manifest_checks.dart",
    "screen_chat_2_fixtures.dart",
)
# Weight above which a file runs alone (it would dominate one aggregate).
MAX_AGG_SECONDS = 20.0

SOURCE_RULES = [
    (re.compile(r"matchesGoldenFile|golden", re.I), "compares goldens"),
    (re.compile(r"\bextends\s+\w*Binding\b|\bwith\s+\w*Binding\b"), "defines its own binding"),
    (re.compile(r"Platform\.script|Isolate\.|exit\("), "uses script path, isolates or exit"),
    (re.compile(r"Directory\.current\s*="), "changes the working directory"),
    (re.compile(r"^@(TestOn|Tags|Skip)\b", re.M), "library-level test annotation"),
]
MAIN_OK = re.compile(r"^void main\(\s*\)\s*(\{|=>)", re.M)


def read_excluded(root: Path) -> dict[str, str]:
    path = root / EXCLUDE_FILE
    out: dict[str, str] = {}
    if path.is_file():
        for line in path.read_text().splitlines():
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            name, _, reason = line.partition("#")
            out[name.strip()] = reason.strip()
    return out


def static_reason(root: Path, rel: str) -> str | None:
    text = (root / rel).read_text(errors="replace")
    if not MAIN_OK.search(text):
        return "main is not a plain void main()"
    for rx, why in SOURCE_RULES:
        if rx.search(text):
            return why
    for helper in GOLDEN_HELPERS:
        if helper in text:
            return "uses a golden helper"
    return None


def eligible(root: Path, files: list[str]) -> list[str]:
    excluded = read_excluded(root)
    return [f for f in files if f not in excluded and static_reason(root, f) is None]


def write_shards(out: Path, groups: dict[int, list[str]]) -> list[Path]:
    out.mkdir(parents=True, exist_ok=True)
    # The suite's per-directory config (fonts off, tolerant goldens) applies to
    # files next to flutter_test_config.dart; mirror it here.
    (out / "flutter_test_config.dart").write_text(
        "// GENERATED by tool/qa/gen_aggregates.py\n"
        "export '../../test/flutter_test_config.dart';\n"
    )
    written = []
    for n, members in sorted(groups.items()):
        lines = [
            "// GENERATED by tool/qa/gen_aggregates.py. Do not edit or commit.",
            "// ignore_for_file: directives_ordering, unused_import",
            "import 'package:flutter_test/flutter_test.dart';",
        ]
        for i, f in enumerate(members):
            lines.append(f"import '../../{f}' as t{i};")
        lines += ["", "void main() {"]
        for i, f in enumerate(members):
            lines.append(f"  group('{f}', t{i}.main);")
        lines.append("}")
        target = out / f"shard_{n}_test.dart"
        target.write_text("\n".join(lines) + "\n")
        (out / f"shard_{n}.txt").write_text("".join(m + "\n" for m in members))
        written.append(target)
    return written


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    e = sub.add_parser("eligible")
    e.add_argument("--root", type=Path, default=Path("."))
    e.add_argument("files", nargs="*")
    w = sub.add_parser("write")
    w.add_argument("--out", type=Path, required=True)
    a = ap.parse_args()
    if a.cmd == "eligible":
        files = a.files or [l.strip() for l in sys.stdin if l.strip()]
        for f in eligible(a.root, files):
            print(f)
        return 0
    groups: dict[int, list[str]] = {}
    for line in sys.stdin:
        line = line.strip()
        if line:
            n, _, f = line.partition(" ")
            groups.setdefault(int(n), []).append(f)
    for p in write_shards(a.out, groups):
        print(p)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
